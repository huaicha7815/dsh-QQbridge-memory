// 生成一份可以直接 push 到 GitHub 的干净副本。
//
// 为什么需要它：这个工作目录里有你的**私人数据**——真实 config.json（QQ 号/令牌）、
// 用户语音库 audio/、运行时 state/、私人人格卡 roles/大肥鱼女儿.md、一堆 *.bak 历史备份。
// 直接 `git init && git add -A` 一定会把它们推上去，而且**推到 GitHub 之后就等于公开了**，
// 事后删除文件也没用（历史里还在，fork 也还在）。
//
// 用法：
//   node scripts/export-public.mjs                  # 生成到 ../qq-bridge-public
//   node scripts/export-public.mjs --out D:/tmp/x   # 指定输出目录
//   node scripts/export-public.mjs --dry-run        # 只报告会复制什么
//
// 生成后它会自己跑一遍隐私扫描，有残留就直接报错退出。
import fs from 'node:fs';
import path from 'node:path';
import { fileURLToPath } from 'node:url';
import { spawnSync } from 'node:child_process';

const root = fileURLToPath(new URL('..', import.meta.url));
const args = process.argv.slice(2);
const dryRun = args.includes('--dry-run');
const outIdx = args.indexOf('--out');
const outDir = path.resolve(outIdx >= 0 ? args[outIdx + 1] : path.join(root, '..', 'qq-bridge-public'));

import { listPublicExportFiles, PUBLIC_GITIGNORE } from './lib/public-export.mjs';

const files = listPublicExportFiles(root);

const totalKB = files.reduce((s, rel) => s + (fs.statSync(path.join(root, rel)).size / 1024), 0);
console.log(`将导出 ${files.length} 个文件，约 ${totalKB.toFixed(0)} KB → ${outDir}`);
if (dryRun) {
  for (const rel of files) console.log(`  ${rel}`);
  process.exit(0);
}

// 清空目标目录（只删我们自己生成的，避免误删用户目录）
if (fs.existsSync(outDir)) {
  const marker = path.join(outDir, '.export-marker');
  if (!fs.existsSync(marker)) {
    console.error(`❌ 目标目录已存在且不是本脚本生成的（缺 .export-marker）：${outDir}`);
    console.error('   为安全起见不覆盖，请换一个目录或手动删除。');
    process.exit(1);
  }
  // ⚠️ 必须保留 .git：这个目录是 git 工作副本，删掉 .git 等于抹掉全部提交历史。
  // （早期版本直接 rmSync 整个目录，踩过一次，提交历史没了。）
  for (const entry of fs.readdirSync(outDir)) {
    if (entry === '.git') continue;
    fs.rmSync(path.join(outDir, entry), { recursive: true, force: true });
  }
}
fs.mkdirSync(outDir, { recursive: true });
fs.writeFileSync(path.join(outDir, '.export-marker'), 'generated by scripts/export-public.mjs\n', 'utf8');

for (const rel of files) {
  const dest = path.join(outDir, rel);
  fs.mkdirSync(path.dirname(dest), { recursive: true });
  fs.copyFileSync(path.join(root, rel), dest);
}
// .gitignore 用脱敏版（不含内部规划文档清单），公开仓库不应暴露内部文件名。
try { fs.writeFileSync(path.join(outDir, '.gitignore'), PUBLIC_GITIGNORE, 'utf8'); } catch {}
console.log(`✅ 已复制 ${files.length} 个文件`);

// 跑一遍隐私扫描（在导出目录里跑，独立于源仓库）
console.log('\n运行隐私扫描…');
const scan = spawnSync(process.execPath, [path.join(outDir, 'scripts', 'privacy-scan.mjs')], {
  cwd: outDir, stdio: 'inherit', timeout: 120000,
});
if (scan.status !== 0) {
  console.error('\n❌ 隐私扫描未通过。先处理上面的问题，再提交。');
  process.exit(1);
}

console.log('\n════ 可以提交了 ════');
console.log(`目录：${outDir}`);
console.log('下一步：');
console.log('  cd ' + outDir);
console.log('  git init && git add -A && git commit -m "init: qq-bridge"');
console.log('  git remote add origin <你的仓库地址>');
console.log('  git push -u origin main');
console.log('\n提交前最后确认一眼：config.json / state/ / audio/ 都不在 git status 里。');
